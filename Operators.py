# Arithmetic
a = 10 + 5      # 15
b = 10 - 5      # 5
c = 10 * 5      # 50
d = 10 / 3      # 3.333...
e = 10 // 3     # 3 (floor division)
f = 10 % 3      # 1 (modulo)
g = 2 ** 3      # 8 (exponent)

# Comparison
print(5 == 5)   # True
print(5 != 3)   # True
print(5 > 3)    # True

# Logical
print(True and False)   # False
print(True or False)    # True
print(not True)         # False

# Assignment
x = 10
x += 5          # x = 15
